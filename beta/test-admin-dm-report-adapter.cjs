"use strict";
const assert=require("node:assert/strict");
const {normalizeBetaConversationReport,mergeAdminDmReports}=require("./admin-dm-report-adapter.cjs");
const beta={id:"11111111-1111-4111-8111-111111111111",reporter_id:"22222222-2222-4222-8222-222222222222",other_user_id:"33333333-3333-4333-8333-333333333333",reason_code:1,details:"Suspicious link",status:"pending",created_at:"2026-10-25T12:00:00Z",evidence_count:2};
const legacy={id:"old-report",reporter_id:"reporter",reported_user_id:"peer",reason:"spam",status:"reviewed",created_at:"2026-10-24T12:00:00Z"};
const normalized=normalizeBetaConversationReport(beta);
assert.equal(normalized.reported_user_id,beta.other_user_id);
assert.equal(normalized.reason,"spam");
assert.equal(normalized.evidence_count,2);
assert.equal(normalized.source,"conversation_beta");
assert.equal(normalizeBetaConversationReport({...beta,reason_code:8}),null);
assert.equal(normalizeBetaConversationReport(null),null);
const merged=mergeAdminDmReports([legacy],[beta]);
assert.equal(merged.length,2);
assert.equal(merged[0].id,beta.id);
assert.equal(merged[1].id,legacy.id);
assert.equal(merged[1].source,"legacy");
assert.equal(legacy.source,undefined,"legacy input must remain untouched");
assert.equal(mergeAdminDmReports(null,null).length,0);
console.log("PASS: admin DM report adapter scenarios");
